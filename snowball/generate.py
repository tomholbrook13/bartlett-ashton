"""Generate daily Snowball puzzles.

Each day's answer is a common 8-letter word. Players start from a 3-letter word
made from its letters and grow it one letter at a time (rearranging freely)
until all eight letters are used.

A word is only kept as an answer if:
  * a chain of common words leads from 3 letters up to it, so hints are fair;
  * it has no other 8-letter anagram in the dictionary, so the finish is unique.

Usage: python3 generate.py [count]   (writes puzzles.js and words.js here)
Requires: pip install wordfreq english-words
"""
import functools
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

from english_words import get_english_words_set
from wordfreq import top_n_list

COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 730
SEED = 20261107
START = "2026-11-07"
L = 8
ANSWER_RANK = 14000  # answers come from the most common words only

BLOCK = set("""
bitching whoring raping rapists molested molester bastards bullshit
diarrhea technica sperling nativism alginate organise arginine bastille boardman
brewster dearborn leighton marcello moreland mulligan therefor retarded vibrator
screwing spanking erection longterm prentice ordinate abortion genocide sherlock
superman thatcher chandler protease neuronal formulae
""".split())

web2 = get_english_words_set(["web2"], lower=False, alpha=True)
gcide = get_english_words_set(["gcide"], lower=False, alpha=True)
proper = {w.lower() for w in web2 if w[:1].isupper()}
lower = {w for w in web2 | gcide if w.islower()}

freq = [w for w in top_n_list("en", 120000) if w.isalpha() and w.isascii() and 3 <= len(w) <= L]
# Words the game accepts: real, lower-case dictionary words seen in ordinary use.
valid = [w for w in freq if w in lower and w not in proper]
valid_set = set(valid)
# Words used for answers and hints: the more common part of that list.
common = set(valid[:30000])


def key(w):
    return "".join(sorted(w))


groups = defaultdict(set)
for w in common:
    groups[key(w)].add(w)
all_groups = defaultdict(set)
for w in valid:
    all_groups[key(w)].add(w)


@functools.lru_cache(None)
def reaches_three(k):
    """True if letters k can be cut back to 3 letters through common words."""
    if len(k) == 3:
        return True
    subs = {k[:i] + k[i + 1:] for i in range(len(k))}
    return any(s in groups and reaches_three(s) for s in subs)


answers = [
    w for w in valid[:ANSWER_RANK]
    if len(w) == L and w in common and w not in BLOCK
    and not (w.endswith("s") and not w.endswith("ss"))
    and len(all_groups[key(w)]) == 1
    and reaches_three(key(w))
]
print(f"{len(answers)} candidate answers, {len(valid)} accepted words", file=sys.stderr)

rng = random.Random(SEED)
rng.shuffle(answers)
puzzles = []
for w in (answers * (COUNT // len(answers) + 1))[:COUNT]:
    bag = list(w)
    while "".join(bag) == w:
        rng.shuffle(bag)
    puzzles.append({"word": w, "bag": "".join(bag)})

here = Path(__file__).parent
(here / "puzzles.js").write_text(
    "// Generated by generate.py. Puzzle n is played on START + n days.\n"
    f"window.SNOWBALL_START = '{START}';\n"
    f"window.SNOWBALL_PUZZLES = {json.dumps(puzzles, separators=(',', ':'))};\n"
)
(here / "words.js").write_text(
    "// Generated by generate.py. Words the game accepts; the first part of the\n"
    "// list is the more common words, which hints prefer.\n"
    f"window.SNOWBALL_COMMON = {len([w for w in valid if w in common])};\n"
    f"window.SNOWBALL_WORDS = '{' '.join([w for w in valid if w in common] + [w for w in valid if w not in common])}';\n"
)
print(f"wrote {len(puzzles)} puzzles", file=sys.stderr)
