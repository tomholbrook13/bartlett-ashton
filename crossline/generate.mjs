// Generate daily Crossline puzzles.
//
// Each day joins two cities with the shortest route over the globe (a great
// circle). The answer is the list of countries that line passes through, not
// counting the two cities' own countries.
//
// A pair is only used if the answer is clear-cut: nudging the line about 25 km
// in any direction must not change which countries it crosses, so there are no
// countries that are only clipped or narrowly missed.
//
// Usage: npm install && node generate.mjs   (writes data.js here)

import { readFileSync, writeFileSync } from "node:fs";
import { geoBounds, geoContains, geoDistance, geoInterpolate } from "d3-geo";
import { feature } from "topojson-client";
import { CITIES, NAMES, MERGE, ALIASES } from "./places.mjs";

const DAYS = Number(process.argv[2] || 365);
const START = "2026-11-07";
const STEP = 0.04;            // sample spacing along the line, in degrees (~4.5 km)
const NUDGE = 0.25;           // how far the line is shifted when testing for near misses, in degrees
const MIN_KM = 40;            // a country must hold this much of the line to count

const world = JSON.parse(readFileSync(new URL("./node_modules/world-atlas/countries-110m.json", import.meta.url)));
const display = name => NAMES[MERGE[name] || name] || MERGE[name] || name;
const countries = feature(world, world.objects.countries).features
  .filter(f => f.properties.name !== "Antarctica")
  .map(f => ({ f, name: display(f.properties.name), b: geoBounds(f) }));

function inBox([lon, lat], [[w, s], [e, n]]) {
  if (lat < s - 0.01 || lat > n + 0.01) return false;
  return w <= e ? lon >= w - 0.01 && lon <= e + 0.01 : lon >= w - 0.01 || lon <= e + 0.01;
}
function countryAt(p) {
  for (const c of countries) if (inBox(p, c.b) && geoContains(c.f, p)) return c.name;
  return null;
}

// Countries along the great circle from a to b, in order, with the km of line inside each.
function trace(a, b) {
  const angle = geoDistance(a, b), deg = angle * 180 / Math.PI;
  const n = Math.ceil(deg / STEP), at = geoInterpolate(a, b), kmPer = angle * 6371 / n;
  const order = [], km = {};
  let last;
  for (let i = 0; i <= n; i++) {
    const c = countryAt(at(i / n));
    if (c) km[c] = (km[c] || 0) + kmPer;
    if (c && c !== last) order.push(c);
    last = c;
  }
  return { order, km, deg };
}

const between = (t, ca, cb) => [...new Set(t.order)].filter(c => c !== ca && c !== cb);
const same = (x, y) => x.length === y.length && x.every(v => y.includes(v));

function judge(A, B) {
  const [, ca, latA, lonA] = A, [, cb, latB, lonB] = B;
  const ga = display(ca), gb = display(cb);
  if (ga === gb) return null;
  const t = trace([lonA, latA], [lonB, latB]);
  if (t.deg < 12 || t.deg > 110) return null;
  // The cities must sit in their own countries on this map, at both ends of the line.
  if (t.order[0] !== ga || t.order[t.order.length - 1] !== gb) return null;
  const mid = between(t, ga, gb);
  if (mid.length < 3 || mid.length > 7) return null;
  if (mid.some(c => t.km[c] < MIN_KM)) return null;
  for (const [dy, dx] of [[NUDGE, 0], [-NUDGE, 0], [0, NUDGE], [0, -NUDGE]]) {
    const t2 = trace([lonA + dx, latA + dy], [lonB + dx, latB + dy]);
    if (!same(between(t2, ga, gb), mid)) return null;
  }
  return { path: mid.filter((c, i) => mid.indexOf(c) === i), km: Math.round(t.deg * Math.PI / 180 * 6371) };
}

// Seeded shuffle of all city pairs, then keep the clear-cut ones.
let seed = 20261108;
const rand = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32);
const pairs = [];
for (let i = 0; i < CITIES.length; i++) for (let j = 0; j < CITIES.length; j++) if (i !== j) pairs.push([i, j]);
for (let i = pairs.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [pairs[i], pairs[j]] = [pairs[j], pairs[i]]; }

const puzzles = [], usedPair = new Set(), cityUse = new Map();
let tried = 0;
for (const [i, j] of pairs) {
  if (puzzles.length >= DAYS) break;
  const key = [i, j].sort().join("-");
  if (usedPair.has(key) || (cityUse.get(i) || 0) >= 6 || (cityUse.get(j) || 0) >= 6) continue;
  tried++;
  const r = judge(CITIES[i], CITIES[j]);
  if (!r) continue;
  usedPair.add(key);
  cityUse.set(i, (cityUse.get(i) || 0) + 1); cityUse.set(j, (cityUse.get(j) || 0) + 1);
  puzzles.push({ a: i, b: j, path: r.path, km: r.km });
  if (puzzles.length % 25 === 0) console.error(`${puzzles.length} puzzles after ${tried} pairs`);
}

const cities = CITIES.map(([name, country, lat, lon]) => [name, display(country), lat, lon]);
writeFileSync(new URL("./data.js", import.meta.url),
  "// Generated by generate.mjs. Puzzle n is played on START + n days.\n" +
  `window.CROSSLINE = ${JSON.stringify({ start: START, names: NAMES, merge: MERGE, aliases: ALIASES, cities, puzzles })};\n`);
writeFileSync(new URL("./world.js", import.meta.url),
  "// Country shapes from world-atlas 2.0.2 (Natural Earth 1:110m, public domain).\n" +
  `window.CROSSLINE_WORLD = ${JSON.stringify(world)};\n`);
console.error(`wrote ${puzzles.length} puzzles (tried ${tried} pairs)`);
for (const p of puzzles.slice(0, 12)) console.error(`${CITIES[p.a][0]} → ${CITIES[p.b][0]} (${p.km} km): ${p.path.join(", ")}`);
