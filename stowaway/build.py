def letters(text):
    """The text's letters, plus the index of the word each letter belongs to."""
    out, owner, word = [], [], 0
    for chunk in re.split(r"(\s+)", text):
        if chunk.isspace():
            word += 1
            continue
        for ch in chunk:
            if ch.isalpha():
                out.append(ch.lower())
                owner.append(word)
    return "".join(out), owner


def crossings(stream, owner, w):
    """Start positions where w appears across a word gap."""
    hits, i = [], stream.find(w)
    while i != -1:
        if owner[i] != owner[i + len(w) - 1]:
            hits.append(i)
        i = stream.find(w, i + 1)
    return hits


here = Path(__file__).parent
puzzles = json.loads((here / "puzzles.json").read_text())
problems = 0
for n, p in enumerate(puzzles, 1):
    stream, owner = letters(p["text"])
    plain = set(re.findall(r"[a-z]+", p["text"].lower()))
    for w in p["words"]:
        if not crossings(stream, owner, w):
            print(f"#{n} {p['theme']}: '{w}' does not run across a gap"); problems += 1
        if w in plain:
            print(f"#{n} {p['theme']}: '{w}' appears as a plain word"); problems += 1
    for w in VOCAB.get(p["theme"], "").split():
        if w not in p["words"] and crossings(stream, owner, w):
            print(f"#{n} {p['theme']}: extra '{w}' hides across a gap"); problems += 1
    print(f"#{n} {p['theme']}: {len(p['words'])} words, {len(p['text'].split())} words of text")

if problems:
    sys.exit(f"{problems} problem(s); puzzles.js not written")
