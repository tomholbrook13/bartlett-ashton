"""Generate daily Tumbler puzzles.

Each puzzle is five common 5-letter words written as columns of a 5x5 grid.
Every row is then rotated by a random amount. The player rotates rows back
until every column spells a word.

A puzzle is only kept if exactly one relative alignment of the rows makes all
five columns valid words (checked against a broad dictionary), so there is
never a "correct but rejected" answer.

Usage: python3 generate.py [count]   (writes puzzles.js next to this file)
Requires: pip install wordfreq english-words
"""
import itertools
import json
import random
import sys
from pathlib import Path

from english_words import get_english_words_set
from wordfreq import top_n_list

N = 5
COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 730
SEED = 20261106

# Names, brands, contractions and words that make a poor daily answer. The
# dictionaries used below include lower-cased first names, so these are
# filtered by hand.
BLOCK = set("""
bitch whore slut penis vagina pussy dicks boobs horny sexes porno nigga negro
rapes raped rapist drunk crack wanks dildo semen sperm urine fucks shits kills
death dying nazis bombs gunny satan queer didnt wasnt arent gotta shalt covid
wanna gonna jihad torah lynch moron idiot gypsy kinky prick bowel vomit booty
jimmy kelly peter henry harry smith japan china trump roger clark billy larry
barry jerry laura terry bobby perry tommy blake costa welsh nancy mason ralph
colin chile singh blair sally randy betty riley jenny mommy molly burke brett
kerry walsh donna allan pablo silva pedro chang irene brock brent monte sonny
malik paddy weber sammy hanna peggy dover bowie jenna clint chevy morse tibet
porto cisco nicky ryder patel reese manny sloan wigan buffy julio levin paolo
cheng ching dixie tammy ethel gemma norma garth emery bosch rowan dutch swiss
clive dunno esque hogan kylie butch twain prima
crore kappa inter blanc mater mamma honda marco wally willy patty kitty piper
""".split())


def five(words):
    return [w for w in words if len(w) == N and w.isalpha() and w.isascii()]


# Lower-case dictionary entries only. A word that web2 also lists as a proper
# noun (Clive, Reese...) is only kept if GCIDE confirms it as a common word.
web2 = get_english_words_set(["web2"], lower=False, alpha=True)
gcide = get_english_words_set(["gcide"], lower=False, alpha=True)
proper = {w.lower() for w in web2 if w[:1].isupper()}
dict_lower = {w for w in web2 | gcide if w.islower()}
common = dict_lower - proper

freq = five(top_n_list("en", 60000))
answers = [
    w for w in freq[:2600]
    if w in common
    and w not in BLOCK
    and not (w.endswith("s") and not w.endswith("ss"))
]
# Anything a player might plausibly type counts as "valid" for ambiguity checks.
valid = set(freq) | {w for w in dict_lower if len(w) == N}
valid_list = sorted(valid)
prefixes = [set(w[:k] for w in valid) for k in range(N + 1)]

print(f"answer pool: {len(answers)}, valid: {len(valid)}", file=sys.stderr)


def solutions(rows):
    """Count relative row offsets (row 0 fixed) where every column is valid."""
    count = 0

    def rec(k, cols):
        nonlocal count
        if k == N:
            count += 1
            return
        row = rows[k]
        for off in range(N):
            new = [cols[c] + row[(c + off) % N] for c in range(N)]
            if all(s in prefixes[k + 1] for s in new):
                rec(k + 1, new)
                if count > 1:
                    return

    rec(1, [rows[0][c] for c in range(N)])
    return count


rng = random.Random(SEED)
puzzles, used = [], set()
attempts = 0
while len(puzzles) < COUNT:
    attempts += 1
    words = rng.sample(answers, N)
    if any(w in used for w in words):
        continue
    rows = ["".join(w[r] for w in words) for r in range(N)]
    if solutions(rows) != 1:
        continue
    # Scramble: row 0 stays put, others shifted by a non-zero amount, and make
    # sure no column happens to read as a word at the start.
    while True:
        offsets = [0] + [rng.randrange(1, N) for _ in range(N - 1)]
        start = [row[o:] + row[:o] for row, o in zip(rows, offsets)]
        if not any("".join(r[c] for r in start) in valid for c in range(N)):
            break
    used.update(words)
    puzzles.append({"rows": start, "words": words})
    if len(used) > len(answers) * 0.8:
        used.clear()  # allow reuse after most of the pool has been seen

print(f"{len(puzzles)} puzzles in {attempts} attempts", file=sys.stderr)
out = Path(__file__).with_name("puzzles.js")
out.write_text(
    "// Generated by generate.py. Puzzle n is played on START_DATE + n days.\n"
    f"window.TUMBLER_START = '2026-11-06';\nwindow.TUMBLER_PUZZLES = {json.dumps(puzzles, separators=(',', ':'))};\n"
)
print(f"wrote {out}", file=sys.stderr)
