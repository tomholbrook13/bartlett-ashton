"""Generate daily Splice puzzles.

Each day has three splices: two words woven together with each word's letters
kept in order (PLANET + ORANGE -> POLRAANNGETE). They get longer through the
day: 4+4, 5+5, then 6+6 letters.

A splice is only kept if exactly one way of pulling its letters into two
sequences gives two dictionary words (of any lengths, 3 letters or more), so
there is never a correct-looking answer that the game rejects.

Usage: python3 generate.py [days]   (writes puzzles.js here)
Requires: pip install wordfreq english-words
"""
import json
import random
import sys
from pathlib import Path

from english_words import get_english_words_set
from wordfreq import top_n_list

DAYS = int(sys.argv[1]) if len(sys.argv) > 1 else 730
SEED = 20261107
START = "2026-11-07"
SIZES = (4, 5, 6)

BLOCK = set("""
bitch whore slut penis pussy dicks boobs horny porno nigga negro rapes raped
rapist dildo semen sperm urine fucks shits nazis satan queer didnt wasnt arent
gotta gonna wanna covid jihad moron idiot gypsy kinky prick vomit booty fuck
shit cunt twat tits arse piss rape anal porn slag cock dick corp
misc info intro admin promo stats stuff dunno
""".split())

web2 = get_english_words_set(["web2"], lower=False, alpha=True)
gcide = get_english_words_set(["gcide"], lower=False, alpha=True)
proper = {w.lower() for w in web2 if w[:1].isupper()}
lower = {w for w in web2 | gcide if w.islower()}

freq = [w for w in top_n_list("en", 80000) if w.isalpha() and w.isascii() and 3 <= len(w) <= 12]
# Anything a player could reasonably offer counts when checking for other answers.
valid = {w for w in freq if w in lower} | {w for w in lower if 3 <= len(w) <= 12}
prefixes = {w[:i] for w in valid for i in range(len(w) + 1)}
# Answers are common, ordinary words.
answers = {n: [] for n in SIZES}
for w in freq[:9000]:
    if (len(w) in SIZES and w in lower and w not in proper and w not in BLOCK
            and not (w.endswith("s") and not w.endswith("ss"))):
        answers[len(w)].append(w)
print({n: len(v) for n, v in answers.items()}, file=sys.stderr)


def splits(s):
    """Count unordered ways to pull s into two valid words (first letter in A)."""
    found = set()

    def rec(i, a, b):
        if len(found) > 1:
            return
        if i == len(s):
            if a in valid and b in valid:
                found.add(tuple(sorted((a, b))))
            return
        ch = s[i]
        if a + ch in prefixes:
            rec(i + 1, a + ch, b)
        if b + ch in prefixes and (a or b):
            rec(i + 1, a, b + ch)

    rec(0, "", "")
    return len(found)


def weave(rng, a, b):
    """Interleave a and b at random, keeping order, and well mixed."""
    while True:
        picks = [0] * len(a) + [1] * len(b)
        rng.shuffle(picks)
        switches = sum(picks[i] != picks[i + 1] for i in range(len(picks) - 1))
        longest = max(len(r) for r in "".join(map(str, picks)).replace("01", "0 1").replace("10", "1 0").split())
        if switches >= len(a) and longest <= 3:
            break
    ia = ib = 0
    out, who = [], []
    for p in picks:
        if p == 0:
            out.append(a[ia]); ia += 1
        else:
            out.append(b[ib]); ib += 1
        who.append(p)
    return "".join(out), who


rng = random.Random(SEED)
used = set()
days = []
for d in range(DAYS):
    day = []
    for n in SIZES:
        while True:
            a, b = rng.sample(answers[n], 2)
            if a in used or b in used or set(a) == set(b):
                continue
            s, who = weave(rng, a, b)
            if splits(s) == 1:
                break
        used.update((a, b))
        if len(used) > 0.7 * sum(len(v) for v in answers.values()):
            used.clear()
        day.append({"s": s, "a": a, "b": b, "who": "".join(map(str, who))})
    days.append(day)

out = Path(__file__).with_name("puzzles.js")
out.write_text(
    "// Generated by generate.py. Day n is played on START + n days; each day has three splices.\n"
    f"window.SPLICE_START = '{START}';\n"
    f"window.SPLICE_DAYS = {json.dumps(days, separators=(',', ':'))};\n"
)
print(f"wrote {len(days)} days", file=sys.stderr)
for day in days[:6]:
    print([(x["s"], x["a"], x["b"]) for x in day], file=sys.stderr)
